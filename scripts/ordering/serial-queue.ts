export class SerialQueue {
  private tail: Promise<void> = Promise.resolve();

  public runAsync<T>(work: () => Promise<T>): Promise<T> {
    const result = this.tail.then(work);
    this.tail = result.then(() => undefined, () => undefined);
    return result;
  }
}
